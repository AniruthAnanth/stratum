/// The zero-copy claim, asserted on identity rather than on a clock (ADR-017):
/// the chunk a fixed-width column was transposed into IS the chunk the frame
/// serves reads from.
#[test]
fn fixed_columns_move_into_the_frame_without_a_copy() {
    let ds = read_dta(fixture("auto.dta")).expect("auto.dta reads");
    let i = ds.index_of("price").expect("auto.dta has price");
    let before = match &ds.cols[i] {
        DtaColumn::Fixed(stratum_data::Column::Int(c)) => c.chunk(0).as_ptr(),
        other => panic!("price is int in auto.dta, got {:?}", other.storage_type()),
    };
    let bridge = ds.into_frame("default").expect("auto.dta bridges");
    let idx = bridge.frame.index_of("price").expect("price survived");
    let after = match bridge.frame.col(idx).expect("column exists") {
        stratum_data::Column::Int(c) => c.chunk(0).as_ptr(),
        other => panic!("price stayed int, got {:?}", other.storage_type()),
    };
    assert_eq!(before, after, "the column was copied, not moved");
}

/// Everything `alltypes.dta` carries beyond the cells: formats, labels,
/// value-label attachment and table, dataset label, characteristics, notes.
#[test]
fn alltypes_metadata_lands_in_the_frame() {
    let ds = read_dta(fixture("alltypes.dta")).expect("alltypes.dta reads");
    let bridge = ds.into_frame("default").expect("alltypes.dta bridges");
    let f = &bridge.frame;

    assert_eq!(f.label(), "All storage types fixture");
    let dbl = f.index_of("v_double").expect("v_double exists");
    let v = f.var(dbl).expect("metadata exists");
    assert_eq!(stratum_data::variable::format_string(&v.format), "%12.4f");
    assert!(v.label.starts_with("A double with a deliberately long"));

    let byte = f.index_of("v_byte").expect("v_byte exists");
    let v = f.var(byte).expect("metadata exists");
    assert_eq!(v.value_label.as_deref(), Some("yesno"));
    let table = f.labels().get("yesno").expect("the table crossed too");
    assert_eq!(table.get(1.0), Some("Yes"));
    assert_eq!(table.get(-1.0), Some("Negative"));

    assert_eq!(
        f.chars().get("_dta", "source"),
        Some("make_fixtures.do"),
        "characteristics cross verbatim"
    );
    assert_eq!(f.chars().get("v_byte", "units"), Some("arbitrary"));
    assert_eq!(
        f.chars().notes("_dta"),
        vec!["this fixture exercises every Stata storage type"]
    );
}

/// The `.dta` sortlist is recorded, not re-proven: the frame claims the order
/// without permuting a single row.
#[test]
fn sorted_dta_records_its_sortlist_without_permuting() {
    let ds = read_dta(fixture("sorted.dta")).expect("sorted.dta reads");
    assert_eq!(ds.sorted_by(), vec!["foreign", "price"], "fixture pin");
    let bridge = ds.into_frame("default").expect("sorted.dta bridges");
    let f = &bridge.frame;
    let sort = f.sort_state();
    assert!(
        sort.valid,
        "the file's claim is trusted, as Stata trusts it"
    );
    let names: Vec<&str> = sort
        .keys
        .iter()
        .map(|k| &*f.var(*k).expect("key names a variable").name)
        .collect();
    assert_eq!(names, vec!["foreign", "price"]);
}

