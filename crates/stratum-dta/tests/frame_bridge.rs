//! `Dataset::into_frame` acceptance: the bridge is lossless, zero-copy where
//! it claims to be, and loud where the engine cannot hold a fact.
//!
//! The round-trip criterion is [`canonical_eq`] — byte identity against a
//! Stata-written fixture is impossible by design (`04` §11.3: uninitialised
//! padding, unobservable strL coalescing). But between two files **this
//! writer** produced from canonically equal datasets, byte identity *is*
//! achievable, and asserting it is the strongest available proof that the
//! bridge dropped nothing: `write(original)` and
//! `write(from_frame(into_frame(original)))` must be the same bytes.
//!
//! Fixtures are the committed `tests/fixtures/dta/` set (W03's, generated by
//! `make_fixtures.do`; never regenerated — the Stata licence has expired).

use std::path::PathBuf;

use stratum_dta::{
    byte_diff, canonical_eq, read_dta, read_dta_bytes, write_dta_to_vec, Dataset, DtaColumn,
    DtaError, DtaReadOptions, DtaVar, DtaWriteOptions, Release, StrLData,
};

fn fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../tests/fixtures/dta")
        .join(name)
}

/// read → into_frame → from_frame → write, asserting canonical equality at
/// every hop and byte identity between the two writes we control.
fn round_trip(name: &str) {
    let ds0 = read_dta(fixture(name)).unwrap_or_else(|e| panic!("{name}: read: {e}"));
    let bridge = ds0
        .clone()
        .into_frame("default")
        .unwrap_or_else(|e| panic!("{name}: into_frame: {e}"));
    assert_eq!(
        bridge.timestamp, ds0.timestamp,
        "{name}: the timestamp must come back through the bridge"
    );
    assert!(
        !bridge.frame.changed(),
        "{name}: a freshly loaded frame is in sync with its file"
    );

    let mut ds1 = Dataset::from_frame(&bridge.frame, ds0.release)
        .unwrap_or_else(|e| panic!("{name}: from_frame: {e}"));
    // The one fact a `Frame` has no slot for, restored from the bridge.
    ds1.timestamp = bridge.timestamp;
    canonical_eq(&ds0, &ds1).unwrap_or_else(|d| panic!("{name}: after the bridge: {d}"));

    let opts = DtaWriteOptions::default();
    let b0 = write_dta_to_vec(&ds0, &opts).unwrap_or_else(|e| panic!("{name}: write ds0: {e}"));
    let b1 = write_dta_to_vec(&ds1, &opts).unwrap_or_else(|e| panic!("{name}: write ds1: {e}"));
    let d = byte_diff(&b0, &b1);
    assert_eq!(
        d.count, 0,
        "{name}: writing the bridged dataset must be byte-identical to writing the original: {d}"
    );

    let ds2 = read_dta_bytes(&b1, &DtaReadOptions::default())
        .unwrap_or_else(|e| panic!("{name}: re-read: {e}"));
    canonical_eq(&ds0, &ds2).unwrap_or_else(|d| panic!("{name}: after write+read: {d}"));
}

